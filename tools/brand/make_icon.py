"""Generate the ミミコピ launcher icon layers from hand-redrawn vector geometry.

The geometry is traced (by eye) from docs/brand/icon-source.png, in that image's
pixel coordinates (1254 x 1254 canvas, mark bbox ~ x 427-825, y 399-827), then
mapped into the 108dp adaptive-icon viewport.

Outputs:
  app/src/main/res/drawable/ic_launcher_foreground.xml   (colour)
  app/src/main/res/drawable/ic_launcher_monochrome.xml   (themed icon)
  docs/brand/icon.svg                                    (full icon, for previews)
Usage: python3 tools/brand/make_icon.py [--preview DIR]  (preview needs cairosvg)
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]

PAPER = "#FEF5E6"
ROSE = "#E6889E"
MUSTARD = "#F3BE52"

# Mark is scaled to 52dp tall: the largest size whose rounded corners stay inside
# the 66dp safe-zone circle of the 108dp canvas.
MARK_CENTER = (626.0, 613.0)
SCALE = 52.0 / 428.0

BODY = ("M528,415 H759 A50,50 0 0 1 809,465 V761 A50,50 0 0 1 759,811 "
        "H528 A50,50 0 0 1 478,761 V465 A50,50 0 0 1 528,415 Z")
BODY_STROKE = 32
RINGS = " ".join(
    f"M452,{cy - 25} H500 A25,25 0 0 1 500,{cy + 25} H452 A25,25 0 0 1 452,{cy - 25} Z"
    for cy in (491, 571, 651, 731))
# Head, stem and flag are separate paths so overlaps never cancel under the
# non-zero fill rule (opposite windings would punch holes).
NOTE = ("M577.3,697.2 A46,36 -22 1 0 662.7,662.8 A46,36 -22 1 0 577.3,697.2 Z",
        "M646,680 V500 H662 V676 Z",
        "M662,500 C670,540 712,548 735,568 C752,584 752,606 742,622 "
        "C746,598 732,582 708,574 C690,568 674,566 662,566 Z")


def group_attrs():
    tx = 54.0 - MARK_CENTER[0] * SCALE
    ty = 54.0 - MARK_CENTER[1] * SCALE
    return tx, ty


def vector_drawable(rose, mustard):
    tx, ty = group_attrs()
    note_paths = "\n".join(
        f"""        <path
            android:fillColor="{mustard}"
            android:pathData="{d}" />""" for d in NOTE)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/make_icon.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="{tx:.4f}"
        android:translateY="{ty:.4f}"
        android:scaleX="{SCALE:.6f}"
        android:scaleY="{SCALE:.6f}">
        <path
            android:pathData="{BODY}"
            android:strokeColor="{rose}"
            android:strokeWidth="{BODY_STROKE}" />
        <path
            android:fillColor="{rose}"
            android:pathData="{RINGS}" />
{note_paths}
    </group>
</vector>
"""


def svg():
    tx, ty = group_attrs()
    note_paths = "\n".join(f'    <path d="{d}" fill="{MUSTARD}"/>' for d in NOTE)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">
  <!-- Generated by tools/brand/make_icon.py -->
  <rect width="108" height="108" fill="{PAPER}"/>
  <g transform="translate({tx:.4f} {ty:.4f}) scale({SCALE:.6f})">
    <path d="{BODY}" fill="none" stroke="{ROSE}" stroke-width="{BODY_STROKE}"/>
    <path d="{RINGS}" fill="{ROSE}"/>
{note_paths}
  </g>
</svg>
"""


def main():
    res = ROOT / "app/src/main/res/drawable"
    res.mkdir(parents=True, exist_ok=True)
    (res / "ic_launcher_foreground.xml").write_text(vector_drawable(ROSE, MUSTARD))
    # Themed icons: the system tints this layer, only alpha matters.
    (res / "ic_launcher_monochrome.xml").write_text(vector_drawable("#FF000000", "#FF000000"))
    (ROOT / "docs/brand/icon.svg").write_text(svg())
    if "--preview" in sys.argv:
        import cairosvg
        out = pathlib.Path(sys.argv[sys.argv.index("--preview") + 1])
        out.mkdir(parents=True, exist_ok=True)
        for px in (512, 192, 48):
            cairosvg.svg2png(bytestring=svg().encode(), write_to=str(out / f"icon-{px}.png"),
                             output_width=px, output_height=px)


if __name__ == "__main__":
    main()
