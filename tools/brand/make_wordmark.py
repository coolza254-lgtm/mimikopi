"""Generate the ミミコピ wordmark as vector paths (no font shipped in the app).

Text is set in Zen Maru Gothic Bold (SIL OFL 1.1), converted to outlines, with
the same eighth note as the launcher icon placed top-right, like
docs/brand/wordmark-source.png.

Usage: python3 tools/brand/make_wordmark.py path/to/ZenMaruGothic-Bold.ttf [--preview DIR]
Font: https://github.com/google/fonts/tree/main/ofl/zenmarugothic
Outputs: app/src/main/res/drawable/wordmark.xml, docs/brand/wordmark.svg
"""
import pathlib
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from make_icon import NOTE, ROSE, ROOT  # noqa: E402

TEXT = "ミミコピ"
TRACKING = -110  # font units between glyphs (full-width advances are loose)


def text_path(font_path):
    font = TTFont(font_path)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    ascent = font["hhea"].ascent
    pen = SVGPathPen(glyphs)
    x = 0
    for ch in TEXT:
        name = cmap[ord(ch)]
        # Flip y (font units are y-up) and shift baseline to the ascent line.
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, ascent)))
        x += glyphs[name].width + TRACKING
    return pen.getCommands(), x - TRACKING, ascent - font["hhea"].descent


def build(font_path):
    d, width, height = text_path(font_path)
    # Note: icon geometry spans roughly x 577-752, y 497-718 (source px).
    note_scale = height * 0.34 / 221
    note_x = width + 70 - 577 * note_scale
    note_y = height * 0.12 - 497 * note_scale
    total_w = width + 70 + 175 * note_scale + 24
    return d, total_w, height, note_scale, note_x, note_y


def vector(d, w, h, ns, nx, ny):
    notes = "\n".join(f"""        <path
            android:fillColor="{ROSE}"
            android:pathData="{p}" />""" for p in NOTE)
    width_dp = 200  # lint VectorRaster: keep vectors <= 200dp
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/make_wordmark.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width_dp}dp"
    android:height="{width_dp * h / w:.1f}dp"
    android:viewportWidth="{w:.1f}"
    android:viewportHeight="{h:.1f}">
    <path
        android:fillColor="{ROSE}"
        android:pathData="{d}" />
    <group
        android:translateX="{nx:.2f}"
        android:translateY="{ny:.2f}"
        android:scaleX="{ns:.5f}"
        android:scaleY="{ns:.5f}">
{notes}
    </group>
</vector>
"""


def svg(d, w, h, ns, nx, ny):
    notes = "\n".join(f'    <path d="{p}"/>' for p in NOTE)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.1f} {h:.1f}" fill="{ROSE}">
  <!-- Generated by tools/brand/make_wordmark.py; text: Zen Maru Gothic Bold (SIL OFL 1.1) -->
  <path d="{d}"/>
  <g transform="translate({nx:.2f} {ny:.2f}) scale({ns:.5f})">
{notes}
  </g>
</svg>
"""


def main():
    args = build(sys.argv[1])
    (ROOT / "app/src/main/res/drawable/wordmark.xml").write_text(vector(*args))
    (ROOT / "docs/brand/wordmark.svg").write_text(svg(*args))
    if "--preview" in sys.argv:
        import cairosvg
        out = pathlib.Path(sys.argv[sys.argv.index("--preview") + 1])
        out.mkdir(parents=True, exist_ok=True)
        cairosvg.svg2png(bytestring=svg(*args).encode(), write_to=str(out / "wordmark.png"),
                         output_width=800, background_color="#FEF5E6")


if __name__ == "__main__":
    main()
