import kotlin.random.Random

/** Five-finger positions: the five keys under the fingers, thumb side first for the right hand. */
enum class HandPosition(val right: List<String>, val left: List<String>, val key: Int) {
    C(listOf("C4", "D4", "E4", "F4", "G4"), listOf("C3", "D3", "E3", "F3", "G3"), 0),
    G(listOf("G4", "A4", "B4", "C5", "D5"), listOf("G2", "A2", "B2", "C3", "D3"), 1),
    D(listOf("D4", "E4", "F#4", "G4", "A4"), listOf("D3", "E3", "F#3", "G3", "A3"), 2),
    F(listOf("F4", "G4", "A4", "Bb4", "C5"), listOf("F3", "G3", "A3", "Bb3", "C4"), -1);

    /** Keys of the position for a hand, lowest first. */
    fun keys(right: Boolean): List<SpelledPitch> = (if (right) this.right else left).map { SpelledPitch.parse(it) }

    /** Key index (0 = lowest) played by finger 1..5: right thumb is lowest, left little finger is lowest. */
    fun indexOf(finger: Int, right: Boolean): Int = if (right) finger - 1 else 5 - finger
}

/**
 * Rhythm cells for E_RHYTHM_TAP and sight reading, one or more whole beats each (quarter = 1). Names: q h h. w
 * notes; qr hr rests; "ee" two eighths; "q.e" dotted quarter + eighth; the 16th cells of learning-system.md 5.3:
 * ssss, ess (1 & a), sse (1 e &), e.s (1 a), ses (1 e a), re (eighth rest + eighth, "&" only).
 */
object RhythmCells {
    /** Durations; negative = rest. */
    val CELLS: Map<String, List<Double>> = mapOf(
        "q" to listOf(1.0), "h" to listOf(2.0), "h." to listOf(3.0), "w" to listOf(4.0),
        "qr" to listOf(-1.0), "hr" to listOf(-2.0),
        "ee" to listOf(0.5, 0.5), "q.e" to listOf(1.5, 0.5),
        "ssss" to listOf(0.25, 0.25, 0.25, 0.25), "ess" to listOf(0.5, 0.25, 0.25), "sse" to listOf(0.25, 0.25, 0.5),
        "e.s" to listOf(0.75, 0.25), "ses" to listOf(0.25, 0.5, 0.25), "re" to listOf(-0.5, 0.5),
    )

    fun beats(cell: String): Int = CELLS.getValue(cell).sumOf { kotlin.math.abs(it) }.toInt()

    private val TOKEN = mapOf(4.0 to "w", 3.0 to "h.", 2.0 to "h", 1.5 to "q.", 1.0 to "q", 0.75 to "e.", 0.5 to "e", 0.25 to "s")

    fun token(duration: Double): String = TOKEN[duration] ?: error("no token for $duration")
}

/** Piece generators for score drills (learning-system.md 5.1 and 5.2). Deterministic per seed. */
object ScoreGenerators {

    fun position(name: String) = HandPosition.valueOf(name)

    /**
     * E_FINGER_PATTERN: [Drill.items] bars of four quarter notes, each bar a finger sequence (no finger twice in a
     * row, no bar equal to the previous one), written with finger numbers in one five-finger position.
     */
    fun fingerPatterns(drill: Drill, seed: Long): PieceFile {
        val rnd = Random(seed)
        val right = drill.hand != "LEFT"
        val pos = position(drill.positions.firstOrNull() ?: "C")
        val keys = pos.keys(right)
        val bars = mutableListOf<List<Int>>()
        while (bars.size < drill.items) {
            val bar = mutableListOf<Int>()
            while (bar.size < 4) {
                val f = rnd.nextInt(1, 6)
                if (bar.lastOrNull() != f && (bar.isNotEmpty() || bars.lastOrNull()?.last() != f)) bar += f
            }
            if (bar != bars.lastOrNull()) bars += bar
        }
        val played = bars.map { bar -> bar.joinToString(" ") { f -> "${keys[pos.indexOf(f, right)]}/q@$f" } }
        val rest = List(bars.size) { "r/w" }
        return PieceFile("gen-fingers-$seed", "รูปแบบนิ้ว", "สร้างโดยแอพ", "Generated by the app", "L1", drill.key ?: pos.key, listOf(4, 4), drill.bpm,
            if (right) played else rest, if (right) rest else played)
    }

    /** E_RHYTHM_TAP: random bars from the rhythm vocabulary on one written note (B4 treble / D3 bass). */
    fun rhythm(drill: Drill, seed: Long): PieceFile {
        val rnd = Random(seed)
        val beatsPerBar = drill.time[0]
        fun bars(vocab: List<String>, note: String): List<String> = List(drill.bars) {
            val cells = mutableListOf<String>()
            var left = beatsPerBar
            while (left > 0) {
                val fits = vocab.filter { RhythmCells.beats(it) <= left }
                require(fits.isNotEmpty()) { "rhythm vocabulary cannot fill a bar of $beatsPerBar beats" }
                val c = fits[rnd.nextInt(fits.size)]
                cells += c
                left -= RhythmCells.beats(c)
            }
            cells.flatMap { RhythmCells.CELLS.getValue(it) }.joinToString(" ") { d ->
                if (d < 0) "r/${RhythmCells.token(-d)}" else "$note/${RhythmCells.token(d)}"
            }
        }
        val whole = List(drill.bars) { restBar(beatsPerBar) }
        val rh = if (drill.hand == "LEFT") whole else bars(drill.rhythms, "B4")
        val lh = when (drill.hand) {
            "LEFT" -> bars(drill.rhythms, "D3")
            "BOTH" -> bars(drill.rhythmsLeft, "D3")
            else -> whole
        }
        return PieceFile("gen-rhythm-$seed", "อ่านจังหวะ", "สร้างโดยแอพ", "Generated by the app", "L1", 0, drill.time, drill.bpm, rh, lh)
    }

    private fun restBar(beats: Int) = when (beats) {
        4 -> "r/w"
        3 -> "r/h."
        2 -> "r/h"
        else -> List(beats) { "r/q" }.joinToString(" ")
    }

    // ---------------- sight reading (5.2) ----------------

    /** What a level allows; used by the generator and by the tests that check its output. */
    data class LevelSpec(
        val level: String,
        val hands: String,
        val positions: List<HandPosition>,
        /** Allowed staff steps between neighbouring notes in one hand (0 = repeat). */
        val steps: Set<Int>,
        val times: List<Int>,
        /** Bar rhythms per beats-per-bar (cells from [RhythmCells]); the last bar uses [endings]. */
        val bars: Map<Int, List<String>>,
        val endings: Map<Int, List<String>>,
        val barCounts: List<Int>,
        /** L4: the hand moves to a second position once, at the middle of the piece. */
        val moves: Boolean = false,
    )

    private val L1_BARS = listOf("q q q q", "q q h", "h q q", "h h", "q h q")
    private val L1_END = listOf("q q h", "h h", "w")
    private val L3_BARS_4 = L1_BARS + listOf("ee q q q", "q ee q q", "q q ee q", "q qr q q", "q q q qr", "ee ee h", "h ee q")
    private val L3_BARS_3 = listOf("q q q", "h q", "q h", "ee q q", "q ee q", "q q qr")
    private val L3_END_3 = listOf("h.", "q h")
    private val L4_BARS_4 = L3_BARS_4 + listOf("h. q", "q h.")
    private val L4_BARS_3 = L3_BARS_3 + listOf("h.")
    private val L5_LEFT = listOf("w", "h h")

    val LEVELS: Map<String, LevelSpec> = listOf(
        LevelSpec("L1", "RIGHT", listOf(HandPosition.C), setOf(0, 1), listOf(4), mapOf(4 to L1_BARS), mapOf(4 to L1_END), listOf(4)),
        LevelSpec("L2", "LEFT", listOf(HandPosition.C), setOf(0, 1), listOf(4), mapOf(4 to L1_BARS), mapOf(4 to L1_END), listOf(4)),
        LevelSpec("L3", "RIGHT", listOf(HandPosition.C, HandPosition.G), setOf(0, 1, 2), listOf(3, 4),
            mapOf(4 to L3_BARS_4, 3 to L3_BARS_3), mapOf(4 to L1_END, 3 to L3_END_3), listOf(4, 8)),
        LevelSpec("L4", "RIGHT", listOf(HandPosition.C, HandPosition.G), setOf(0, 1, 2, 3, 4), listOf(3, 4),
            mapOf(4 to L4_BARS_4, 3 to L4_BARS_3), mapOf(4 to L1_END, 3 to L3_END_3), listOf(8), moves = true),
        LevelSpec("L5", "BOTH", listOf(HandPosition.C, HandPosition.G, HandPosition.F), setOf(0, 1, 2), listOf(4),
            mapOf(4 to L1_BARS), mapOf(4 to L1_END), listOf(8)),
    ).associateBy { it.level }

    /** The tonic letter of a key signature (major keys used in stages 1-3). */
    fun tonic(key: Int): Letter = when (key) {
        0 -> Letter.C; 1 -> Letter.G; 2 -> Letter.D; -1 -> Letter.F
        else -> error("unsupported key $key")
    }

    /**
     * E_READ_PIECE: a new short piece within the level (hand, positions, steps, rhythms, metre, bars); it ends on
     * the tonic. [Drill.hand] picks the hand for L3/L4 when given as LEFT; [Drill.positions] replaces the level's positions;
     * [Drill.alternate] makes L5 hands take turns bar by bar.
     */
    fun sightReading(drill: Drill, seed: Long): PieceFile {
        val spec = LEVELS.getValue(drill.level)
        val rnd = Random(seed)
        val allowed = drill.positions.map { position(it) }.ifEmpty { spec.positions }
        val beats = spec.times[rnd.nextInt(spec.times.size)]
        val barCount = spec.barCounts[rnd.nextInt(spec.barCounts.size)]
        val hands = if (spec.hands == "RIGHT" && drill.hand == "LEFT" && spec.level in setOf("L3", "L4")) "LEFT" else spec.hands
        val right = hands != "LEFT"

        // Positions: one, or (L4) two with a move at the middle. Mixed positions share key C.
        val first = allowed[rnd.nextInt(allowed.size)]
        val second = if (spec.moves) allowed.filter { it != first }.let { if (it.isEmpty()) first else it[rnd.nextInt(it.size)] } else first
        val key = drill.key ?: if (first == second) first.key.takeIf { first == HandPosition.F || first == HandPosition.D } ?: 0 else 0
        val tonic = tonic(key)
        val positionOfBar = { bar: Int -> if (bar < barCount / 2) first else second }

        val rhythms = List(barCount) { bar ->
            val pool = if (bar == barCount - 1) spec.endings.getValue(beats) else spec.bars.getValue(beats)
            pool[rnd.nextInt(pool.size)].split(" ")
        }
        // L5 turns: the right hand plays odd bars (1, 3, ...) and the last bar; it rests in the others.
        val turns = hands == "BOTH" && drill.alternate
        val rightPlays = { b: Int -> !turns || b % 2 == 0 || b == barCount - 1 }
        val melody = melody(rnd, rhythms.mapIndexed { b, c -> if (rightPlays(b)) c else emptyList() }, positionOfBar, right, spec.steps, tonic)
        val melodyBars = rhythms.mapIndexed { b, cells ->
            if (!rightPlays(b)) return@mapIndexed restBar(beats)
            var k = 0
            cells.flatMap { RhythmCells.CELLS.getValue(it) }.joinToString(" ") { d ->
                if (d < 0) "r/${RhythmCells.token(-d)}" else "${melody[b][k++]}/${RhythmCells.token(d)}"
            }
        }
        val rest = List(barCount) { restBar(beats) }
        val (rh, lh) = when (hands) {
            "RIGHT" -> melodyBars to rest
            "LEFT" -> rest to melodyBars
            else -> {
                // L5: left hand holds the position's root or fifth (whole or two halves); ends on the tonic.
                val leftKeys = first.keys(right = false)
                val leftBars = List(barCount) { b ->
                    val last = b == barCount - 1
                    val tonicLeft = leftKeys.first { it.letter == tonic }
                    val pattern = if (last) "w" else L5_LEFT[rnd.nextInt(L5_LEFT.size)]
                    pattern.split(" ").joinToString(" ") { cell ->
                        val p = if (last) tonicLeft else listOf(leftKeys[0], leftKeys[4])[rnd.nextInt(2)]
                        "$p/$cell"
                    }
                }
                if (drill.alternate) {
                    // Turns: the right hand plays odd bars (1, 3, ...), the left hand even bars; both end together.
                    val r = melodyBars
                    val l = leftBars.mapIndexed { b, s -> if (b % 2 == 1 || b == barCount - 1) s else rest[b] }
                    r to l
                } else {
                    melodyBars to leftBars
                }
            }
        }
        return PieceFile("gen-read-${drill.level}-$seed", "บทอ่านใหม่ ${drill.level}", "สร้างโดยแอพ", "Generated by the app",
            drill.level, key, listOf(beats, 4), drill.bpm, rh, lh)
    }

    /**
     * Notes for every sounding cell, as a random walk inside the bar's position with allowed steps, never three
     * repeats in a row, ending on the tonic. Retries until a valid walk is found.
     */
    private fun melody(
        rnd: Random,
        rhythms: List<List<String>>,
        positionOfBar: (Int) -> HandPosition,
        right: Boolean,
        steps: Set<Int>,
        tonic: Letter,
    ): List<List<SpelledPitch>> {
        val counts = rhythms.map { cells -> cells.flatMap { RhythmCells.CELLS.getValue(it) }.count { it > 0 } }
        val total = counts.sum()
        repeat(500) {
            val notes = mutableListOf<Pair<Int, Int>>() // (bar, index in that bar's position)
            var ok = true
            for (b in counts.indices) for (k in 0 until counts[b]) {
                val pos = positionOfBar(b)
                val keys = pos.keys(right)
                val n = notes.size
                val isLast = n == total - 1
                val prev = notes.lastOrNull()
                val candidates = (0..4).filter { idx ->
                    val p = keys[idx]
                    when {
                        prev == null -> p.letter == tonic || idx in setOf(0, 2, 4)
                        positionOfBar(prev.first) != pos -> true // the hand just moved: free
                        else -> {
                            val prevPitch = positionOfBar(prev.first).keys(right)[prev.second]
                            val step = kotlin.math.abs(p.diatonicIndex - prevPitch.diatonicIndex)
                            val threeRepeats = step == 0 && n >= 2 &&
                                positionOfBar(notes[n - 2].first).keys(right)[notes[n - 2].second] == prevPitch
                            step in steps && !threeRepeats
                        }
                    }
                }.filter { idx -> !isLast || keys[idx].letter == tonic }
                if (candidates.isEmpty()) { ok = false; break }
                // Prefer small steps: weight 3 for repeat/step, 1 otherwise.
                val weighted = candidates.flatMap { idx ->
                    val prevPitch = prev?.let { positionOfBar(it.first).keys(right)[it.second] }
                    val step = prevPitch?.let { kotlin.math.abs(keys[idx].diatonicIndex - it.diatonicIndex) } ?: 0
                    List(if (step <= 1) 3 else 1) { idx }
                }
                notes += b to weighted[rnd.nextInt(weighted.size)]
            }
            if (ok && notes.size == total) {
                return counts.indices.map { b -> notes.filter { it.first == b }.map { (bar, idx) -> positionOfBar(bar).keys(right)[idx] } }
            }
        }
        error("could not build a melody")
    }

    // ---------------- interval reading ----------------

    /** E_INTERVAL_READ: [Drill.items] sets of natural notes on one clef within [low, high], neighbours a set step apart. */
    fun intervalSets(drill: Drill, seed: Long): List<List<SpelledPitch>> {
        val rnd = Random(seed)
        val low = SpelledPitch.parse(drill.low).diatonicIndex
        val high = SpelledPitch.parse(drill.high).diatonicIndex
        fun natural(index: Int) = SpelledPitch(Letter.entries[index % 7], 0, index / 7)
        val out = mutableListOf<List<SpelledPitch>>()
        while (out.size < drill.items) {
            val set = mutableListOf(rnd.nextInt(low, high + 1))
            var guard = 0
            while (set.size < drill.notesPerSet && guard++ < 200) {
                val step = drill.intervals[rnd.nextInt(drill.intervals.size)]
                val up = rnd.nextBoolean()
                val next = set.last() + if (up) step else -step
                if (next in low..high) set += next
            }
            if (set.size == drill.notesPerSet && set.zipWithNext().any { (a, b) -> a != b }) out += set.map(::natural)
        }
        return out
    }

    fun clefOf(drill: Drill): Clef = if (drill.clef == "bass") Clef.BASS else Clef.TREBLE
}
