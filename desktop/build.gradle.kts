/**
 * The screens ported from the Android app (desktop/.../port) keep their `R.string.x` and `R.drawable.x` references:
 * this writes an `R` object with the same names from the Android resources, the string values, the icon files and the
 * list of bundled content files (the classpath cannot list a folder inside the jar).
 */
abstract class GeneratePortSources : DefaultTask() {
    @get:InputFile @get:PathSensitive(PathSensitivity.RELATIVE) abstract val strings: RegularFileProperty
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val drawables: DirectoryProperty
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val content: DirectoryProperty
    @get:OutputDirectory abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        val doc = javax.xml.parsers.DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(strings.get().asFile)
        val nodes = doc.getElementsByTagName("string")
        val names = ArrayList<String>()
        val values = ArrayList<String>()
        for (i in 0 until nodes.length) {
            val e = nodes.item(i) as org.w3c.dom.Element
            names += e.getAttribute("name")
            values += androidText(e.textContent)
        }
        val icons = drawables.get().asFile.listFiles().orEmpty().map { it.name }.filter { it.endsWith(".xml") }.sorted()
        val base = content.get().asFile
        val files = base.walkTopDown().filter { it.isFile && it.name.endsWith(".json") }.map { it.relativeTo(base).invariantSeparatorsPath }.sorted().toList()
        val out = StringBuilder()
        out.append("// Generated by :desktop:generatePortSources from the Android app's resources. Do not edit.\n")
        out.append("@file:Suppress(\"ClassName\", \"ObjectPropertyName\", \"unused\")\n\npackage com.id.mimikopi.desktop.port\n\n")
        out.append("object R {\n    object string {\n")
        names.forEachIndexed { i, n -> out.append("        const val `").append(n).append("` = ").append(i).append('\n') }
        out.append("    }\n    object drawable {\n")
        icons.forEachIndexed { i, n -> out.append("        const val `").append(n.removeSuffix(".xml")).append("` = ").append(i).append('\n') }
        out.append("    }\n}\n\n")
        fun array(name: String, items: List<String>) {
            out.append("internal val ").append(name).append(": Array<String> = arrayOf(\n")
            items.forEach { out.append("    ").append(literal(it)).append(",\n") }
            out.append(")\n\n")
        }
        array("STRING_VALUES", values)
        array("DRAWABLE_FILES", icons)
        array("CONTENT_FILES", files)
        val dir = output.get().asFile.resolve("com/id/mimikopi/desktop/port")
        dir.mkdirs()
        dir.resolve("R.kt").writeText(out.toString())
    }

    /** Android's reading of a string resource: backslash escapes, quotes dropped, whitespace collapsed and trimmed. */
    private fun androidText(raw: String): String {
        val sb = StringBuilder()
        var i = 0
        var space = false
        while (i < raw.length) {
            val c = raw[i]
            if (c == '\\' && i + 1 < raw.length) {
                val n = raw[i + 1]
                i += 2
                when (n) {
                    'n' -> sb.append('\n')
                    't' -> sb.append('\t')
                    'u' -> { sb.append(raw.substring(i, i + 4).toInt(16).toChar()); i += 4 }
                    else -> sb.append(n)
                }
                space = false
                continue
            }
            if (c == '"') { i++; continue }
            if (c.isWhitespace()) { if (!space) sb.append(' '); space = true } else { sb.append(c); space = false }
            i++
        }
        return sb.toString().trim()
    }

    private fun literal(s: String): String =
        "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$").replace("\n", "\\n").replace("\t", "\\t") + "\""
}

val generatePortSources = tasks.register<GeneratePortSources>("generatePortSources") {
    strings.set(layout.projectDirectory.file("../app/src/main/res/values/strings.xml"))
    drawables.set(layout.projectDirectory.dir("../app/src/main/res/drawable"))
    content.set(layout.projectDirectory.dir("../content"))
    output.set(layout.buildDirectory.dir("generated/port"))
}

